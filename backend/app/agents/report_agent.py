"""
TANA AI - Report Agent
Generates professional PDF reports in English and Amharic.
"""

from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.lib.colors import HexColor
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
)
from reportlab.lib.enums import TA_CENTER
from backend.app.core.config import OUTPUT_DIR


NAVY = HexColor("#0A1628")
CYAN = HexColor("#00D9FF")
GREEN = HexColor("#078930")
YELLOW = HexColor("#FCDD09")
RED = HexColor("#DA121A")
GRAY = HexColor("#8892B0")

AMHARIC_FONT = "NotoEthiopic"


class ReportAgent:
    def __init__(self, target, recon, scan, compliance):
        self.target = target
        self.recon = recon
        self.scan = scan
        self.compliance = compliance
        self.timestamp = datetime.now()
        self.styles = getSampleStyleSheet()
        self._register_fonts()
        self._setup_styles()

    def _register_fonts(self):
        try:
            pdfmetrics.registerFont(TTFont(
                AMHARIC_FONT,
                "/usr/share/fonts/truetype/noto/NotoSansEthiopic-Regular.ttf"
            ))
            print("[TANA AI] Amharic font registered")
        except Exception as e:
            print(f"[TANA AI] Warning: Amharic font failed: {e}")

    def _setup_styles(self):
        self.styles.add(ParagraphStyle(
            name="TanaTitle", fontSize=24, textColor=CYAN,
            alignment=TA_CENTER, spaceAfter=10, fontName="Helvetica-Bold"
        ))
        self.styles.add(ParagraphStyle(
            name="TanaSubtitle", fontSize=12, textColor=GRAY,
            alignment=TA_CENTER, spaceAfter=30
        ))
        self.styles.add(ParagraphStyle(
            name="TanaHeading", fontSize=16, textColor=NAVY,
            spaceBefore=20, spaceAfter=10, fontName="Helvetica-Bold"
        ))
        self.styles.add(ParagraphStyle(
            name="TanaBody", fontSize=11, textColor=NAVY, spaceAfter=6
        ))
        self.styles.add(ParagraphStyle(
            name="TanaAmharic", fontName=AMHARIC_FONT,
            fontSize=12, textColor=NAVY, spaceAfter=6
        ))

    def generate(self):
        timestamp_str = self.timestamp.strftime("%Y%m%d_%H%M%S")
        safe_target = self.target.replace(".", "_").replace("/", "_")
        filename = OUTPUT_DIR / f"TANA_REPORT_{safe_target}_{timestamp_str}.pdf"

        doc = SimpleDocTemplate(
            str(filename), pagesize=A4,
            topMargin=2*cm, bottomMargin=2*cm,
            leftMargin=2*cm, rightMargin=2*cm
        )

        story = []
        story.extend(self._build_cover())
        story.append(PageBreak())
        story.extend(self._build_executive_summary())
        story.extend(self._build_recon_section())
        story.extend(self._build_scan_section())
        story.extend(self._build_compliance_section())
        story.extend(self._build_recommendations())
        story.extend(self._build_footer())

        doc.build(story)
        print(f"[TANA AI] PDF report generated: {filename}")
        return str(filename)

    def _build_cover(self):
        return [
            Spacer(1, 4*cm),
            Paragraph("TANA AI", self.styles["TanaTitle"]),
            Paragraph(
                "Autonomous Penetration Testing & Compliance Platform",
                self.styles["TanaSubtitle"]
            ),
            Spacer(1, 2*cm),
            Paragraph("<i>From the Source, Security Flows</i>", self.styles["TanaSubtitle"]),
            Spacer(1, 3*cm),
            Paragraph(f"<b>Target:</b> {self.target}", self.styles["TanaBody"]),
            Paragraph(f"<b>Date:</b> {self.timestamp.strftime('%B %d, %Y')}", self.styles["TanaBody"]),
            Paragraph(f"<b>Time:</b> {self.timestamp.strftime('%H:%M:%S')}", self.styles["TanaBody"]),
            Spacer(1, 3*cm),
            Paragraph("Generated by TANA AI", self.styles["TanaBody"]),
            Paragraph("Built in Ethiopia, for Ethiopia", self.styles["TanaBody"]),
        ]

    def _build_executive_summary(self):
        s = self.scan
        elements = [
            Paragraph("Executive Summary", self.styles["TanaHeading"]),
            Paragraph(
                f"This report presents the results of an autonomous security assessment "
                f"conducted by TANA AI against <b>{self.target}</b>.",
                self.styles["TanaBody"]
            ),
            Spacer(1, 0.5*cm),
        ]
        data = [
            ["Metric", "Value"],
            ["Open Ports Discovered", str(len(self.recon.get("ports", [])))],
            ["Total Vulnerabilities", str(s.get("total", 0))],
            ["Critical", str(s.get("critical", 0))],
            ["High", str(s.get("high", 0))],
            ["Medium", str(s.get("medium", 0))],
            ["Low", str(s.get("low", 0))],
        ]
        table = Table(data, colWidths=[8*cm, 6*cm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("TEXTCOLOR", (0, 0), (-1, 0), CYAN),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("ALIGN", (1, 0), (1, -1), "CENTER"),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
            ("GRID", (0, 0), (-1, -1), 0.5, GRAY),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1),
             [HexColor("#F5F5F5"), HexColor("#FFFFFF")]),
        ]))
        elements.append(table)
        elements.append(Spacer(1, 0.5*cm))
        return elements

    def _build_recon_section(self):
        elements = [
            Paragraph("1. Reconnaissance Results", self.styles["TanaHeading"]),
            Paragraph(
                "TANA AI discovered the following open ports and services:",
                self.styles["TanaBody"]
            ),
            Spacer(1, 0.3*cm),
        ]
        data = [["Port", "Protocol", "Service", "Version"]]
        for svc in self.recon.get("services", []):
            data.append([
                str(svc["port"]), svc["protocol"], svc["service"],
                svc.get("version", "")[:40]
            ])
        if len(data) > 1:
            table = Table(data, colWidths=[2*cm, 2.5*cm, 3*cm, 6.5*cm])
            table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("TEXTCOLOR", (0, 0), (-1, 0), CYAN),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("GRID", (0, 0), (-1, -1), 0.5, GRAY),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1),
                 [HexColor("#F5F5F5"), HexColor("#FFFFFF")]),
            ]))
            elements.append(table)
        elements.append(Spacer(1, 0.5*cm))
        return elements

    def _build_scan_section(self):
        elements = [
            Paragraph("2. Vulnerability Findings", self.styles["TanaHeading"]),
            Paragraph(
                f"TANA AI identified <b>{self.scan.get('total', 0)}</b> vulnerabilities:",
                self.styles["TanaBody"]
            ),
            Spacer(1, 0.3*cm),
        ]
        for i, finding in enumerate(self.scan.get("findings", [])[:20]):
            severity = finding.get("severity", "unknown").upper()
            color = {
                "CRITICAL": RED,
                "HIGH": HexColor("#FF6B00"),
                "MEDIUM": YELLOW,
                "LOW": GREEN
            }.get(severity, GRAY)
            style = ParagraphStyle(
                name=f"finding_{severity}_{i}",
                parent=self.styles["TanaBody"],
                textColor=color,
                fontName="Helvetica-Bold"
            )
            elements.append(Paragraph(
                f"[{severity}] {finding.get('name', 'Unknown')}", style
            ))
            elements.append(Paragraph(
                f"    {finding.get('matched', '')}", self.styles["TanaBody"]
            ))
        elements.append(Spacer(1, 0.5*cm))
        return elements

    def _build_compliance_section(self):
        c = self.compliance
        elements = [
            Paragraph("3. Compliance Assessment", self.styles["TanaHeading"]),
            Paragraph(
                "<b>Ethiopian Cybersecurity Legal Framework</b>",
                self.styles["TanaBody"]
            ),
            Spacer(1, 0.3*cm),
        ]

        if c.get("is_critical_sector"):
            classification = "CRITICAL INFRASTRUCTURE"
            color = "#DA121A"
        else:
            classification = "Standard Target"
            color = "#078930"

        elements.append(Paragraph(
            f"<b>Classification:</b> <font color='{color}'>{classification}</font>",
            self.styles["TanaBody"]
        ))

        if c.get("is_critical_sector"):
            sector = c.get("matched_sector", {})
            elements.append(Paragraph(
                f"<b>Critical Sector:</b> {sector.get('name', 'Unknown')}",
                self.styles["TanaBody"]
            ))
            amharic_name = sector.get('name_am', '')
            if amharic_name:
                elements.append(Paragraph(
                    "<b>Critical Sector (Amharic):</b>",
                    self.styles["TanaBody"]
                ))
                elements.append(Paragraph(amharic_name, self.styles["TanaAmharic"]))

        elements.append(Spacer(1, 0.3*cm))
        elements.append(Paragraph(
            "<b>Proclamation 1426/2026 - Critical Infrastructure Cybersecurity</b>",
            self.styles["TanaBody"]
        ))

        if c.get("cert_report_required"):
            elements.append(Paragraph(
                "<b><font color='#DA121A'>CERT REPORT REQUIRED WITHIN 48 HOURS</font></b>",
                self.styles["TanaBody"]
            ))
            elements.append(Paragraph(
                f"<b>Fine if Neglected:</b> ETB {c.get('fine_range_etb', 'N/A')}",
                self.styles["TanaBody"]
            ))

        elements.append(Spacer(1, 0.3*cm))
        elements.append(Paragraph(
            "<b>Legal Requirements:</b>", self.styles["TanaBody"]
        ))
        for req in c.get("legal_requirements", []):
            elements.append(Paragraph(
                f"  - {req}", self.styles["TanaBody"]
            ))

        if c.get("general_recommendations"):
            elements.append(Spacer(1, 0.3*cm))
            elements.append(Paragraph(
                "<b>General Security Recommendations:</b>",
                self.styles["TanaBody"]
            ))
            for rec in c.get("general_recommendations", []):
                elements.append(Paragraph(
                    f"  - {rec}", self.styles["TanaBody"]
                ))

        elements.append(Spacer(1, 0.5*cm))
        return elements

    def _build_recommendations(self):
        elements = [
            Paragraph("4. Recommendations", self.styles["TanaHeading"]),
            Paragraph(
                "TANA AI recommends the following actions:",
                self.styles["TanaBody"]
            ),
            Spacer(1, 0.3*cm),
        ]
        recommendations = [
            "Patch all identified vulnerabilities according to severity level.",
            "Update SSH configurations to disable weak algorithms.",
            "Disable Apache directory listing to prevent information disclosure.",
            "Conduct regular security audits (every 30 days minimum).",
            "Implement continuous monitoring with a SOC.",
            "Train staff on secure configuration practices.",
        ]
        if self.compliance.get("cert_report_required"):
            recommendations.insert(
                0,
                "URGENT: Report all critical/high findings to Ethio-CERT within 48 hours."
            )
        for i, rec in enumerate(recommendations, 1):
            elements.append(Paragraph(
                f"  {i}. {rec}", self.styles["TanaBody"]
            ))
        elements.append(Spacer(1, 0.5*cm))
        return elements

    def _build_footer(self):
        return [
            Spacer(1, 1*cm),
            Paragraph(
                "<i>This report was generated autonomously by TANA AI.</i>",
                self.styles["TanaSubtitle"]
            ),
            Paragraph(
                "TANA AI - Built in Ethiopia, for Ethiopia",
                self.styles["TanaSubtitle"]
            ),
        ]
